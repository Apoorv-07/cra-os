interface ReportSection {
  id: string;
  heading: string;
  kind: 'prose' | 'list' | 'table' | 'metrics';
  body?: string;
  items?: Array<{ title: string; detail?: string; tone?: 'neutral' | 'warning' | 'critical' | 'good' }>;
  table?: { columns: string[]; rows: Array<Array<string | number>> };
  metrics?: Array<{ label: string; value: string; description?: string }>;
}

function buildReadinessReport(orgId: string, repositoryId: string | undefined, orgName: string) {
  const db = getDb();
  const repo = repositoryId ? db.select().from(repositories).where(eq(repositories.id, repositoryId)).get() : null;
  if (repositoryId && (!repo || repo.orgId !== orgId)) throw AppError.notFound('Repository');

  const scope = repo ? (repo.fullName ?? repo.name ?? orgName) : orgName;
  const { result } = evaluateScope(orgId, repositoryId);

  const artefacts = db
    .select()
    .from(evidence)
    .where(and(eq(evidence.orgId, orgId), ...(repositoryId ? [eq(evidence.repositoryId, repositoryId)] : [])))
    .orderBy(desc(evidence.createdAt))
    .all();

  const totals = result.totals as Record<string, number>;
  const sections: ReportSection[] = [
    {
      id: 'summary',
      heading: 'Where you stand',
      kind: 'prose',
      body:
        result.score >= 85
          ? `${scope} scores ${Math.round(result.score)} out of 100 (grade ${result.grade}). Most CRA expectations are met with evidence; the remaining work is listed below.`
          : result.score >= 60
            ? `${scope} scores ${Math.round(result.score)} out of 100 (grade ${result.grade}). The foundations are in place, but ${(totals.missing ?? 0) + (totals.needsReview ?? 0)} expectation${(totals.missing ?? 0) + (totals.needsReview ?? 0) === 1 ? '' : 's'} still need attention before this would stand up to scrutiny.`
            : `${scope} scores ${Math.round(result.score)} out of 100 (grade ${result.grade}). Significant gaps remain: start with the actions below, then re-scan to see the score move.`,
    },
    {
      id: 'metrics',
      heading: 'How the score is made up',
      kind: 'metrics',
      metrics: [
        { label: 'Readiness', value: `${Math.round(result.score)} / 100`, description: `Grade ${result.grade}` },
        { label: 'Met', value: String(totals.passed ?? 0), description: 'Controls with supporting evidence' },
        { label: 'Partially met', value: String(totals.partial ?? 0), description: 'In place but incomplete' },
        { label: 'Needs attention', value: String((totals.missing ?? 0) + (totals.needsReview ?? 0)), description: 'Gaps or unconfirmed controls' },
        { label: 'Not applicable', value: String(totals.not_applicable ?? 0) },
      ],
    },
    {
      id: 'actions',
      heading: 'What to do next',
      kind: 'list',
      items: (result.actions ?? []).slice(0, 8).map((action) => ({ title: action.title, detail: action.rationale, tone: 'warning' as const })),
    },
    {
      id: 'controls',
      heading: 'Control by control',
      kind: 'table',
      table: {
        columns: ['Expectation', 'Status', 'Why CRAOS reached this conclusion'],
        rows: result.assessments.map((a) => [controlTitle(a.controlId), humanStatus(a.status), a.rationale]),
      },
    },
  ];

  if (artefacts.length > 0) {
    sections.push({
      id: 'evidence',
      heading: 'Evidence behind this assessment',
      kind: 'table',
      table: {
        columns: ['Evidence', 'Type', 'Collected', 'Checksum'],
        rows: artefacts.slice(0, 50).map((e) => [e.title, humanEvidenceType(e.type), new Date(e.createdAt).toISOString().slice(0, 10), (e.sha256 ?? '—').slice(0, 16)]),
      },
    });
  }

  return {
    kind: 'readiness' as const,
    scope,
    score: result.score,
    grade: result.grade,
    sections,
    evidenceCount: artefacts.length,
    disclaimer: DISCLAIMER,
  };
}

function buildFindingsReport(orgId: string, repositoryId: string | undefined, orgName: string) {
  const db = getDb();
  const repo = repositoryId ? db.select().from(repositories).where(eq(repositories.id, repositoryId)).get() : null;
  if (repositoryId && (!repo || repo.orgId !== orgId)) throw AppError.notFound('Repository');
  const scope = repo ? repo.fullName ?? repo.name : orgName;

  const repoRows = repositoryId
    ? [repo!]
    : db.select().from(repositories).where(and(eq(repositories.orgId, orgId), eq(repositories.status, 'active'))).all();
  const scanIds = repoRows.map((r) => r.lastScanId).filter((id): id is string => Boolean(id));

  const links = scanIds.length
    ? db.select().from(componentVulnerabilities).where(and(eq(componentVulnerabilities.orgId, orgId))).all().filter((l) => scanIds.includes(l.scanId))
    : [];
  const comps = scanIds.length ? db.select().from(componentsTable).all().filter((c) => scanIds.includes(c.scanId)) : [];
  const vulnById = new Map(db.select().from(vulnerabilities).all().map((v) => [v.id, v]));
  const compById = new Map(comps.map((c) => [c.id, c]));
  const repoById = new Map(repoRows.map((r) => [r.id, r]));

  const rows = links
    .map((link) => ({ link, component: compById.get(link.componentId), vulnerability: vulnById.get(link.vulnerabilityId) }))
    .filter((r) => r.component && r.vulnerability)
    .map(({ link, component, vulnerability }) => ({
      state: link.state,
      priority: priorityOf({
        severity: vulnerability!.severity,
        kevFlag: vulnerability!.kevFlag,
        epssScore: vulnerability!.epssScore,
        exploitability: link.exploitability,
        exposure: link.exposure,
        state: link.state,
      }),
      severity: vulnerability!.severity,
      kevFlag: vulnerability!.kevFlag,
      text: headlineFor({
        componentName: component!.name,
        version: component!.version,
        severity: vulnerability!.severity,
        kevFlag: vulnerability!.kevFlag,
        exploitability: link.exploitability,
        repositoryName: repoById.get(link.repositoryId)?.fullName ?? 'Repository',
      }),
      why: whyItMatters({
        kevFlag: vulnerability!.kevFlag,
        epssScore: vulnerability!.epssScore,
        exploitability: link.exploitability,
        exposure: link.exposure,
        severity: vulnerability!.severity,
        state: link.state,
      }),
      fix: link.remediation ?? (link.fixedVersion ? `Upgrade ${component!.name} to ${link.fixedVersion}.` : 'No fixed version published yet'),
    }))
    .filter((r) => r.state === 'open');

  const order = { act_now: 0, prioritise: 1, monitor: 2, review: 3 } as const;
  rows.sort(
    (a, b) =>
      order[a.priority] - order[b.priority] ||
      riskScore({
        severity: b.severity,
        kevFlag: b.kevFlag,
        epssScore: null,
        exploitability: null,
        exposure: null,
      }) -
        riskScore({
          severity: a.severity,
          kevFlag: a.kevFlag,
          epssScore: null,
          exploitability: null,
          exposure: null,
        }),
  );

  const actNow = rows.filter((r) => r.priority === 'act_now');
  const prioritise = rows.filter((r) => r.priority === 'prioritise');

  const sections: ReportSection[] = [
    {
      id: 'summary',
      heading: 'Where you stand',
      kind: 'prose',
      body:
        rows.length === 0
          ? `${scope} has no open findings in the latest scans. Keep monitoring: new advisories are matched automatically.`
          : `${scope} has ${rows.length} open finding${rows.length === 1 ? '' : 's'}. ${actNow.length} need${actNow.length === 1 ? 's' : ''} action now, ${prioritise.length} should be prioritised${actNow.length === 0 && prioritise.length === 0 ? '.' : ', and the rest can follow your normal cycle.'}`,
    },
    {
      id: 'metrics',
      heading: 'At a glance',
      kind: 'metrics',
      metrics: [
        { label: 'Open findings', value: String(rows.length) },
        { label: 'Act now', value: String(actNow.length), description: 'Known exploited or actively exploited' },
        { label: 'Prioritise', value: String(prioritise.length), description: 'Critical or high severity' },
        { label: 'Repositories affected', value: String(new Set(links.map((l) => l.repositoryId)).size) },
      ],
    },
  ];

  if (actNow.length > 0) {
    sections.push({
      id: 'act-now',
      heading: 'Act now',
      kind: 'list',
      items: actNow.slice(0, 20).map((r) => ({ title: r.text, detail: `${r.why} Fix: ${r.fix}`, tone: 'critical' as const })),
    });
  }
  if (prioritise.length > 0) {
    sections.push({
      id: 'prioritise',
      heading: 'Prioritise',
      kind: 'list',
      items: prioritise.slice(0, 30).map((r) => ({ title: r.text, detail: `Fix: ${r.fix}`, tone: 'warning' as const })),
    });
  }

  sections.push({
    id: 'register',
    heading: 'Full findings register',
    kind: 'table',
    table: {
      columns: ['Finding', 'Severity', 'Recommended action'],
      rows: rows.slice(0, 200).map((r) => [r.text, humanSeverity(r.severity), r.fix]),
    },
  });

  return {
    kind: 'findings' as const,
    scope,
    sections,
    evidenceCount: 0,
    disclaimer: DISCLAIMER,
  };
}

function buildEvidencePackReport(orgId: string, repositoryId: string | undefined, orgName: string) {
  const db = getDb();
  const repo = repositoryId ? db.select().from(repositories).where(eq(repositories.id, repositoryId)).get() : null;
  if (repositoryId && (!repo || repo.orgId !== orgId)) throw AppError.notFound('Repository');
  const scope = repo ? repo.fullName ?? repo.name : orgName;

  const artefacts = db
    .select()
    .from(evidence)
    .where(and(eq(evidence.orgId, orgId), ...(repositoryId ? [eq(evidence.repositoryId, repositoryId)] : [])))
    .orderBy(desc(evidence.createdAt))
    .all();

  const { result } = evaluateScope(orgId, repositoryId);
  const scan = repo?.lastScanId ? db.select().from(scans).where(eq(scans.id, repo.lastScanId)).get() : null;

  const sections: ReportSection[] = [
    {
      id: 'summary',
      heading: 'Purpose',
      kind: 'prose',
      body: `This pack collects the evidence CRA Compliance OS holds for ${scope}. Each item is stored with a SHA-256 checksum and a timestamp, so the pack can be handed to an auditor or customer as-is.`,
    },
    {
      id: 'metrics',
      heading: 'Coverage',
      kind: 'metrics',
      metrics: [
        { label: 'Artefacts', value: String(artefacts.length) },
        { label: 'Readiness', value: `${Math.round(result.score)} / 100`, description: `Grade ${result.grade}` },
        { label: 'Components tracked', value: String(scan?.componentCount ?? 0) },
        { label: 'Last scan', value: scan?.finishedAt ? new Date(scan.finishedAt).toISOString().slice(0, 10) : 'No scan yet' },
      ],
    },
    {
      id: 'register',
      heading: 'Evidence register',
      kind: 'table',
      table: {
        columns: ['Artefact', 'Type', 'Collected', 'SHA-256'],
        rows: artefacts.map((e) => [e.title, humanEvidenceType(e.type), new Date(e.createdAt).toISOString().slice(0, 10), e.sha256 ?? '—']),
      },
    },
    {
      id: 'controls',
      heading: 'What this evidence supports',
      kind: 'table',
      table: {
        columns: ['Expectation', 'Status', 'Conclusion'],
        rows: result.assessments.map((a) => [controlTitle(a.controlId), humanStatus(a.status), a.rationale]),
      },
    },
  ];

  return {
    kind: 'evidence_pack' as const,
    scope,
    score: result.score,
    grade: result.grade,
    sections,
    evidenceCount: artefacts.length,
    disclaimer: DISCLAIMER,
  };
}

