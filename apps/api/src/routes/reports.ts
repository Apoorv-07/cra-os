/** Control titles live in the catalogue, so reports read as English, not IDs. */
function controlTitle(controlId: string): string {
  return CONTROL_CATALOGUE.find((c) => c.id === controlId)?.title ?? controlId;
}

function humanStatus(status: string): string {
  return (
    {
      passed: 'Met',
      partial: 'Partially met',
      missing: 'Needs attention',
      needs_review: 'Needs confirmation',
      not_applicable: 'Not applicable',
    } as Record<string, string>
  )[status] ?? status;
}

function humanSeverity(severity: string | null): string {
  return (
    { critical: 'Critical', high: 'High', medium: 'Medium', low: 'Low', unknown: 'Unrated' } as Record<string, string>
  )[severity ?? 'unknown'] ?? 'Unrated';
}

function humanEvidenceType(type: string): string {
  return (
    {
      document: 'Policy or procedure',
      remediation: 'Remediation record',
      report: 'Test or audit report',
      sbom: 'Software inventory (SBOM)',
      scan: 'Scan result',
      incident: 'Incident record',
      other: 'Other',
    } as Record<string, string>
  )[type] ?? type;
}

export { humanStatus, humanSeverity, humanEvidenceType };
