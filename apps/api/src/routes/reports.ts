/**
 * Reports.
 *
 * A report is a **document**, not a screenshot of a dashboard: it has a title, a
 * purpose, a scope and sections that read top to bottom, and every claim in it
 * carries the evidence that supports it. Reports are stored, versioned by
 * generation time, and shareable through a revocable token.
 */

const DISCLAIMER =
  'This report is engineering evidence generated by CRA Compliance OS from repository and advisory data. It supports CRA compliance work; it is not legal advice and does not constitute a conformity assessment or CE marking.';

const createSchema = z.object({
  kind: z.enum(['readiness', 'findings', 'evidence_pack']),
  repositoryId: z.string().optional(),
  title: z.string().min(3).max(160).optional(),
});

/**
 * Evaluates either one repository or the whole organisation.
 *
 * The engine is repository-scoped by design, so an organisation-level report
 * aggregates: the score is the mean across active repositories, and each
 * control reports the *worst* status found anywhere in the estate — an
 * organisation is only as compliant as its weakest repository.
 */
function evaluateScope(orgId: string, repositoryId: string | undefined) {
  const db = getDb();

  if (repositoryId) {
    const result = evaluate(buildContext({ orgId, repositoryId }));
    return { result, repositoriesCovered: 1 };
  }

  const repos = db.select().from(repositories).where(and(eq(repositories.orgId, orgId), eq(repositories.status, 'active'))).all();
  if (repos.length === 0) {
    const result = evaluate(buildContext({ orgId, repositoryId: '' }));
    return { result, repositoriesCovered: 0 };
  }

  const perRepo = repos.map((r) => ({ repo: r, result: evaluate(buildContext({ orgId, repositoryId: r.id })) }));
  const score = Math.round(perRepo.reduce((sum, p) => sum + p.result.score, 0) / perRepo.length);
  const grade = gradeFor(score);

  const STATUS_RANK: Record<string, number> = { missing: 0, needs_review: 1, partial: 2, passed: 3, not_applicable: 4 };
  const byControl = new Map<string, { status: string; score: number; confidence: string; rationale: string; evidence: string[]; remediation: string }>();

  for (const { repo, result: r } of perRepo) {
    for (const a of r.assessments ?? []) {
      const existing = byControl.get(a.controlId);
      if (!existing) {
        byControl.set(a.controlId, { ...a });
        continue;
      }
      const rank = (s: string) => STATUS_RANK[s] ?? 5;
      if (rank(a.status) < rank(existing.status)) {
        const repoName = repo.fullName ?? repo.name ?? 'a repository';
        byControl.set(a.controlId, {
          ...a,
          rationale: `${a.rationale} (Worst result across the estate: ${repoName}.)`,
        });
      }
    }
  }

  const totals = {
    passed: [...byControl.values()].filter((a) => a.status === 'passed').length,
    partial: [...byControl.values()].filter((a) => a.status === 'partial').length,
    missing: [...byControl.values()].filter((a) => a.status === 'missing').length,
    needsReview: [...byControl.values()].filter((a) => a.status === 'needs_review').length,
    notApplicable: [...byControl.values()].filter((a) => a.status === 'not_applicable').length,
  };

  const actions = perRepo
    .flatMap(({ repo, result: r }) => (r.actions ?? []).map((a) => ({ ...a, repository: repo.fullName ?? repo.name ?? 'Repository' })))
    .sort((a, b) => b.impact - a.impact)
    .slice(0, 8);

  return {
    result: {
      score,
      grade,
      totals,
      domains: perRepo[0]?.result.domains ?? [],
      assessments: [...byControl.entries()].map(([controlId, a]) => ({ controlId, ...a })),
      actions,
    },
    repositoriesCovered: perRepo.length,
  };
}

/** The engine grades a repository; an aggregate score needs the same scale. */
function gradeFor(score: number): string {
  if (score >= 90) return 'A';
  if (score >= 75) return 'B';
  if (score >= 60) return 'C';
  if (score >= 40) return 'D';
  return 'E';
}

function actionFor(kind: string) {
  if (kind === 'readiness') return 'report.readiness' as const;
  if (kind === 'findings') return 'report.findings' as const;
  return 'report.evidence_pack' as const;
}

function defaultTitle(kind: string, scope: string) {
  const label = kind === 'readiness' ? 'CRA readiness report' : kind === 'findings' ? 'Findings report' : 'Evidence pack';
  return `${label} — ${scope}`;
}

