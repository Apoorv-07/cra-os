reportsRoutes.get('/:orgId/reports', requireAuth, requireOrg('viewer'), async (c) => {
  const orgId = c.get('orgId')!;
  const rows = getDb()
    .select()
    .from(reports)
    .where(eq(reports.orgId, orgId))
    .orderBy(desc(reports.createdAt))
    .all();

  const shares = getDb().select().from(shareLinks).where(eq(shareLinks.orgId, orgId)).all();
  const shareByResource = new Map(shares.filter((s) => !s.revokedAt).map((s) => [s.resourceId, s]));

  return ok(
    c,
    rows.map((r) => {
      const share = shareByResource.get(r.id);
      return {
        id: r.id,
        kind: r.kind,
        title: r.title,
        status: r.status,
        repositoryId: r.repositoryId,
        creditsCharged: r.creditsCharged,
        createdAt: r.createdAt,
        shared: Boolean(share),
        shareToken: share?.token ?? null,
        shareExpiresAt: share?.expiresAt ?? null,
        shareViewCount: share?.viewCount ?? 0,
      };
    }),
  );
});

reportsRoutes.get('/:orgId/reports/:reportId', requireAuth, requireOrg('viewer'), async (c) => {
  const orgId = c.get('orgId')!;
  const reportId = c.req.param('reportId');
  const row = getDb().select().from(reports).where(eq(reports.id, reportId)).get();
  if (!row || row.orgId !== orgId) throw AppError.notFound('Report');

  const share = getDb()
    .select()
    .from(shareLinks)
    .where(and(eq(shareLinks.resourceId, reportId), eq(shareLinks.resourceType, 'report')))
    .get();

  const org = getDb().select().from(organizations).where(eq(organizations.id, orgId)).get();

  return ok(c, {
    id: row.id,
    kind: row.kind,
    title: row.title,
    status: row.status,
    createdAt: row.createdAt,
    repositoryId: row.repositoryId,
    creditsCharged: row.creditsCharged,
    organisation: org?.name ?? 'Organisation',
    share: share && !share.revokedAt ? { token: share.token, expiresAt: share.expiresAt, viewCount: share.viewCount, lastViewedAt: share.lastViewedAt } : null,
    content: row.contentJson ? JSON.parse(row.contentJson) : null,
  });
});

reportsRoutes.post('/:orgId/reports', requireAuth, requireOrg('member'), async (c) => {
  const orgId = c.get('orgId')!;
  const auth = c.get('auth')!;
  const body = await parseBody(c, createSchema);

  const org = getDb().select().from(organizations).where(eq(organizations.id, orgId)).get();
  const orgName = org?.name ?? 'Organisation';

  // Charge first: a report we cannot pay for is never generated.
  const reservation = reserveCredits({
    orgId,
    userId: auth.user.id,
    action: actionFor(body.kind),
    resourceType: body.repositoryId ? 'repository' : 'organization',
    resourceId: body.repositoryId ?? orgId,
    free: !env.BILLING_ENABLED,
  });

  const built =
    body.kind === 'readiness'
      ? buildReadinessReport(orgId, body.repositoryId, orgName)
      : body.kind === 'findings'
        ? buildFindingsReport(orgId, body.repositoryId, orgName)
        : buildEvidencePackReport(orgId, body.repositoryId, orgName);

  const id = newId('rep');
  const title = body.title?.trim() || defaultTitle(body.kind, built.scope);

  getDb()
    .insert(reports)
    .values({
      id,
      orgId,
      repositoryId: body.repositoryId ?? null,
      kind: body.kind,
      title,
      status: 'ready',
      contentJson: JSON.stringify({ ...built, organisation: orgName, generatedAt: Date.now() }),
      creditsCharged: reservation.credits,
      createdByUserId: auth.user.id,
      createdAt: Date.now(),
      updatedAt: Date.now(),
    })
    .run();

  audit({
    orgId,
    action: 'report.generated',
    targetType: 'report',
    targetId: id,
    meta: { kind: body.kind, repositoryId: body.repositoryId ?? null, credits: reservation.credits },
    actorUserId: auth.user.id,
  });

  return created(c, { id, title, kind: body.kind, creditsCharged: reservation.credits });
});

const shareSchema = z.object({ expiresInDays: z.number().int().min(1).max(365).optional() });

reportsRoutes.post('/:orgId/reports/:reportId/share', requireAuth, requireOrg('admin'), async (c) => {
  const orgId = c.get('orgId')!;
  const auth = c.get('auth')!;
  const reportId = c.req.param('reportId');
  const body = await parseBody(c, shareSchema);

  const report = getDb().select().from(reports).where(eq(reports.id, reportId)).get();
  if (!report || report.orgId !== orgId) throw AppError.notFound('Report');

  const existing = getDb()
    .select()
    .from(shareLinks)
    .where(and(eq(shareLinks.resourceId, reportId), eq(shareLinks.resourceType, 'report')))
    .get();

  if (existing && !existing.revokedAt) {
    return ok(c, { token: existing.token, expiresAt: existing.expiresAt, alreadyShared: true });
  }

  const token = randomToken(24);
  const expiresAt = body.expiresInDays ? Date.now() + body.expiresInDays * 86_400_000 : null;

  if (existing) {
    // Re-sharing a revoked link keeps the audit trail and revokes the old token.
    getDb()
      .update(shareLinks)
      .set({ token, expiresAt, revokedAt: null, viewCount: 0, lastViewedAt: null, createdAt: Date.now(), createdByUserId: auth.user.id })
      .where(eq(shareLinks.id, existing.id))
      .run();
  } else {
    getDb()
      .insert(shareLinks)
      .values({
        id: newId('shr'),
        orgId,
        resourceType: 'report',
        resourceId: reportId,
        token,
        expiresAt,
        createdByUserId: auth.user.id,
        createdAt: Date.now(),
      })
      .run();
  }

  audit({ orgId, action: 'report.shared', targetType: 'report', targetId: reportId, meta: { expiresAt }, actorUserId: auth.user.id });

  return created(c, { token, expiresAt, url: `/share/${token}` });
});

reportsRoutes.delete('/:orgId/reports/:reportId/share', requireAuth, requireOrg('admin'), async (c) => {
  const orgId = c.get('orgId')!;
  const auth = c.get('auth')!;
  const reportId = c.req.param('reportId');

  const share = getDb()
    .select()
    .from(shareLinks)
    .where(and(eq(shareLinks.resourceId, reportId), eq(shareLinks.resourceType, 'report')))
    .get();
  if (!share || share.orgId !== orgId) throw AppError.notFound('Share link');

  getDb().update(shareLinks).set({ revokedAt: Date.now() }).where(eq(shareLinks.id, share.id)).run();
  audit({ orgId, action: 'report.share_revoked', targetType: 'report', targetId: reportId, actorUserId: auth.user.id });

  return ok(c, { revoked: true });
});

reportsRoutes.delete('/:orgId/reports/:reportId', requireAuth, requireOrg('admin'), async (c) => {
  const orgId = c.get('orgId')!;
  const reportId = c.req.param('reportId');
  const report = getDb().select().from(reports).where(eq(reports.id, reportId)).get();
  if (!report || report.orgId !== orgId) throw AppError.notFound('Report');

  getDb().delete(shareLinks).where(eq(shareLinks.resourceId, reportId)).run();
  getDb().delete(reports).where(eq(reports.id, reportId)).run();
  audit({ orgId, action: 'report.deleted', targetType: 'report', targetId: reportId });

  return ok(c, { deleted: true });
});

